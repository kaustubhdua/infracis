/**
 * Escape untrusted text before placing it inside Leaflet popup HTML.
 * Prefer DOM text nodes where possible; this helper is for the existing popup template.
 */
export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => {
    switch (character) {
      case "&": return "&amp;";
      case "<": return "&lt;";
      case ">": return "&gt;";
      case '"': return "&quot;";
      case "'": return "&#39;";
      default: return character;
    }
  });
}
